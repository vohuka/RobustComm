"""Synthetic smoke-test demo orchestration (shared by the CLI and the demo script)."""
from __future__ import annotations

from pathlib import Path
from typing import Any

from ..utils.io import ensure_dir, load_yaml, write_run_metadata
from ..utils.logging import get_logger
from ..utils.seeding import set_global_seed
from ..utils.validation import validate_config
from .plot_results import make_all_plots
from .run_ablation import run_ablation
from .run_evaluation import run_evaluation

_log = get_logger(__name__)

_NOTE = (
    "synthetic smoke-test output, not a paper result.\n"
    "Generated by RobustComm on the built-in SyntheticCommEnv. These numbers exercise the\n"
    "pipeline and demonstrate the qualitative claim (robust aggregation retains reward\n"
    "under attack while the mean collapses); they are NOT the paper's benchmark results.\n"
    "Provision a real environment adapter (DIAL/MPE/SMAC) on EC2 to produce real results.\n"
)


def run_demo(config_path: str | Path) -> dict[str, Any]:
    cfg = validate_config(load_yaml(config_path))
    rng = set_global_seed(int(cfg["seed"]))
    out = cfg["output"]["dir"]
    ensure_dir(out)
    write_run_metadata(cfg, out, int(cfg["seed"]))

    _log.info("running evaluation sweep (synthetic)...")
    eval_df = run_evaluation(cfg, rng, out)
    _log.info("running ablation (synthetic)...")
    abl_df = run_ablation(cfg, rng, out)
    _log.info("generating plots...")
    plots = make_all_plots(out, f"{out}/plots")

    (Path(out) / "README.txt").write_text(_NOTE, encoding="utf-8")
    return {
        "out_dir": str(out),
        "eval_rows": int(len(eval_df)),
        "ablation_rows": int(len(abl_df)),
        "plots": [str(p) for p in plots],
        "note": _NOTE.splitlines()[0],
    }
